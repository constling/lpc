/** 去除单个词两侧的括号/标点后再查词典(输出时保留原标点)。 */
function lookupToken(token: string): string {
  const key = token.replace(/^[()]+|[()]+$/g, "").toLowerCase();
  const translated = WORDS[key];
  if (translated !== undefined) {
    const prefix = token.match(/^[()]+/)?.[0] ?? "";
    const suffix = token.match(/[()]+$/)?.[0] ?? "";
    return `${prefix}${translated}${suffix}`;
  }
  return token;
}

/** 是否还有未命中的单词(纯数字/标点 token 不算,直接透传)。 */
function hasUntranslatedToken(tokens: string[], translated: string[]): boolean {
  for (let i = 0; i < tokens.length; i++) {
    const hasLetters = /[A-Za-z]/.test(tokens[i]);
    if (hasLetters && translated[i] === tokens[i]) {
      return true;
    }
  }
  return false;
}

/**
 * 将英文显示名翻译为中文:
 * 1. 先整词匹配短语词典;
 * 2. 再按空格拆词,逐词查单词词典,相邻译文直接拼接(中文无需空格);
 * 3. 任一含字母的单词未命中时返回原文(全有或全无,避免半英半中)。
 */
export function translateText(text: string | null | undefined): string {
  if (!text) return text ?? "";
  const trimmed = text.trim();
  if (!trimmed) return text;

  const phrase = PHRASES[trimmed.toLowerCase()];
  if (phrase !== undefined) return phrase;

  const tokens = trimmed.split(/\s+/);
  const translatedTokens = tokens.map(lookupToken);
  if (hasUntranslatedToken(tokens, translatedTokens)) {
    return text;
  }
  return translatedTokens.join("");
}
